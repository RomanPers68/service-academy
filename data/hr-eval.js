// ── переписка эталона: вопросы интервьюера (по порядку тем) и ответы кандидата + план (тема, уточнение) ──
export function evalMessages(c) {
  const qs = Q[c.role] || Q.waiter;
  const msgs = [], plan = [];
  let k = -1;
  for (const x of c.qa) {
    if (x.f) {
      msgs.push({ role: "assistant", content: EVAL_FOLLOW });
      plan.push({ topic: x.t, followup: true });
    } else {
      k += 1;
      const q = (qs[k] || qs[0])[x.v ? 1 : 0];
      const lead = k === 0 ? `Здравствуйте, ${c.name}! Давайте просто пообщаемся: я расскажу пару рабочих ситуаций, а вы поделитесь, как бы поступили. ` : "Спасибо, понятно. ";
      msgs.push({ role: "assistant", content: lead + q });
      plan.push({ topic: k, followup: false });
    }
    msgs.push({ role: "user", content: x.a });
  }
  return { messages: msgs, plan };
}
