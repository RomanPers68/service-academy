/** v142 (Доп. 461): какие пункты чек-листа не отмечены. items — [{ id, text }], checked — id отмеченных. */
export function clLeft(items, checked) {
  const on = new Set(Array.isArray(checked) ? checked : []);
  return (Array.isArray(items) ? items : []).filter((x) => x && x.id && !on.has(x.id)).map((x) => String(x.text || "").trim()).filter(Boolean);
}

/** Строка под «Закрытие: отмечено 6 из 7» в «Утре руководителя»: «Не отмечено: «ЕГАИС и ЭДО…»» (два пункта и «и ещё N»). */
export function clLeftLine(left) {
  const l = Array.isArray(left) ? left.filter(Boolean) : [];
  if (!l.length) return null;
  const shown = l.slice(0, 2).map((t) => "«" + t + "»").join(", ");
  return "Не отмечено: " + shown + (l.length > 2 ? " и ещё " + (l.length - 2) : "");
}
