// импортов: общее для сервера (api/web-answer.js, mode "desc" — с поиском в интернете) и приложения (ui/menu-trainer.jsx —
// без интернета, через Наставника) и демо.
//
// Владелец (13.11): «И я думаю будет полезно ассистенту, который дописывает варианты вкусного описания блюд, что бы было
// больше и разнообразнее описаний😉». Было: три варианта, всегда одни и те же углы (вкус, происхождение, игриво). Стало: пять
// вариантов за нажатие, у каждого свой угол из десяти; следующее нажатие — другие пять углов, а уже показанное модель не
// повторяет. С интернетом модель ищет, откуда блюдо, как его готовят по традиции и чем особенны ингредиенты, — для фактов
// и идей; текст пишет сама. Ингредиенты — только из состава: у гостя могут быть аллергии.

export const DESC_N = 5;
/** Углы описания: [ключ, подпись на экране, подсказка модели]. За нажатие — DESC_N подряд, следующее — следующие. */
export const DESC_ANGLES = [
  ["taste", "Вкус и текстура", "про вкус и текстуру: что гость почувствует"],
  ["origin", "Откуда блюдо", "откуда блюдо и как его готовят по традиции"],
  ["play", "Коротко и игриво", "одна короткая игривая фраза"],
  ["doubt", "Если гость сомневается", "для гостя, который сомневается: почему стоит взять"],
  ["star", "Главный ингредиент", "что особенного в главном ингредиенте"],
  ["craft", "Как готовим", "как готовим и подаём — только то, что следует из состава и пометок"],
  ["mood", "Под настроение", "к какому случаю, времени дня или сезону"],
  ["simple", "Простыми словами", "простыми словами для гостя, который блюдо не знает"],
  ["gourmet", "Для гурмана", "для гурмана: детали и оттенки вкуса"],
  ["fact", "Интересный факт", "интересный факт или маленькая история о блюде"],
];
export const DESC_LABEL = Object.fromEntries(DESC_ANGLES.map(([k, l]) => [k, l]));
/** Углы нажатия номер round (0, 1, 2…): по кругу, по DESC_N. */
export function descAngles(round = 0) {
  const n = DESC_ANGLES.length, r = Math.max(0, Math.floor(Number(round) || 0)), k = (r * DESC_N) % n;
  return [...DESC_ANGLES.slice(k), ...DESC_ANGLES.slice(0, k)].slice(0, DESC_N);
}

const s = (v, n) => String(v == null ? "" : v).replace(/\s+/g, " ").trim().slice(0, n);
const ingOf = (v) => (Array.isArray(v) ? v : String(v || "").split(",")).map((x) => s(x, 60)).filter(Boolean).slice(0, 30);

/** Правила — одни и те же с интернетом и без. */
export const DESC_RULES = `1. Упоминай только ингредиенты из состава блюда и то, что в пометках ресторана. Ничего не добавляй: у гостя могут быть
   аллергии, а повар готовит по своей технологической карте.
2. Факты о происхождении, истории и технике — только те, в которых уверен. Не уверен — пиши о вкусе.
3. Без цен, скидок, граммовок и обещаний, которых нет в данных («домашняя», «фермерская», «мраморная» — только если это есть
   в составе или пометках).
4. По-русски, тёплым живым языком официанта, без пафоса и штампов («изысканный», «непревзойдённый», «гастрономическое
   путешествие»), без перечисления ингредиентов подряд. Каждое описание — 1–2 предложения.
5. Все варианты разные: по углу, по словам и по началу фразы. Уже показанные варианты не повторяй.`;

/** Системная подсказка для ответа с поиском в интернете (api/web-answer.js, mode "desc"). */
export const DESC_SYSTEM = `Ты — автор меню и шеф-наставник ресторана: пишешь «вкусные описания» блюд, которые официант говорит гостю. У тебя
есть поиск в интернете: найди, откуда блюдо, как его готовят по традиции, чем особенны его ингредиенты, какими словами
описывают похожие блюда. Это для фактов и идей — текст пиши сам, фразы с сайтов не копируй; факты о блюде бери только те,
что подтверждают найденные страницы. Правила:
${DESC_RULES}`;

/**
 * Вопрос модели. dish — { name, cat, ingredients, note }; seen — уже показанные варианты (и то, что в карточке); round —
 * номер нажатия; web — с поиском (ответ JSON) или без (через Наставника: пронумерованные абзацы — так надёжнее).
 */
export function descPrompt({ restaurant = "", dish = {}, seen = [], round = 0, web = false } = {}) {
  const d = dish || {}, ing = ingOf(d.ingredients), angles = descAngles(round);
  const prev = (Array.isArray(seen) ? seen : []).map((x) => s(x, 300)).filter(Boolean).slice(-15);
  const head = web ? "" : "Напиши «вкусные описания» блюда для гостя: их говорит официант. Правила:\n" + DESC_RULES + "\n\n";
  return head + (restaurant ? "Ресторан: «" + s(restaurant, 80) + "».\n" : "") + "Блюдо: «" + s(d.name, 120) + "»" + (s(d.cat, 60) ? " (раздел: " + s(d.cat, 60) + ")" : "") + ".\n"
    + "Состав: " + (ing.join(", ") || "не указан") + "." + (s(d.note, 300) ? "\nПометки ресторана: " + s(d.note, 300) + "." : "")
    + "\n\nНапиши " + angles.length + " вариантов, по одному на каждый угол:\n" + angles.map(([k, , hint], i) => (i + 1) + ". " + (web ? k + " — " : "") + hint).join("\n")
    + (prev.length ? "\n\nУже показаны — не повторяй ни мысль, ни начало фразы:\n" + prev.map((x) => "— " + x).join("\n") : "")
    + (web ? '\n\nОтвет — только JSON-массив без пояснений: [{"angle": "' + angles[0][0] + '", "text": "…"}, …]; angle — ключ угла из списка выше.'
      : "\n\nФормат ответа строго: " + angles.length + " абзацев по порядку углов, каждый начинается с «1.», «2.» и так далее. Без кавычек, заголовков и пояснений.");
}

const key = (t) => String(t || "").toLowerCase().replace(/ё/g, "е").replace(/[^а-яa-z0-9]+/g, " ").trim();
// кавычки снимаем, только если весь вариант в них обёрнут («Текст»): «Название» в начале фразы остаётся с обеими кавычками
const tidy = (t) => {
  const x = s(String(t || "").replace(/\[\[[^\]]*\]\]/g, ""), 400).replace(/^[*•\s—-]+/, "").trim();
  return /^["“«]/.test(x) && /["”»]$/.test(x) && (x.match(/["“”«»]/g) || []).length === 2 ? x.slice(1, -1).trim() : x;
};
/**
 * Ответ модели → [{ angle, label, text }] — до DESC_N, без повторов и без того, что уже показывали. JSON-массив
 * ([{ angle, text }] или строки), иначе пронумерованные абзацы; угол — из ответа, иначе по порядку.
 */
export function descParse(text, round = 0, seen = []) {
  const keys = descAngles(round).map((a) => a[0]);
  const raw = String(text || "").replace(/```(json)?/gi, "").trim();
  let arr = null;
  const a = raw.indexOf("["), b = raw.lastIndexOf("]");
  if (a >= 0 && b > a) { try { arr = JSON.parse(raw.slice(a, b + 1)); } catch (e) { arr = null; } }
  // абзацы «1. …», «2. …»: угол — по номеру (вступление до «1.» не в счёт); без номеров — весь ответ одним вариантом
  const plain = raw.replace(/\[\[[^\]]*\]\]/g, "");
  const numbered = [...plain.matchAll(/(?:^|\n)\s*([1-9])[.)]\s*([\s\S]*?)(?=\n\s*[1-9][.)]\s|$)/g)].map((m) => ({ angle: keys[Number(m[1]) - 1] || "", text: tidy(m[2]) }));
  const fromJson = Array.isArray(arr) ? arr.map((x, i) => (x && typeof x === "object"
    ? { angle: keys.includes(x.angle) ? x.angle : keys[i] || "", text: tidy(x.text) } : { angle: keys[i] || "", text: tidy(x) })) : [];
  const list = fromJson.some((v) => v.text.length > 20) ? fromJson : numbered.length ? numbered : [{ angle: keys[0], text: tidy(plain) }];
  const old = new Set((Array.isArray(seen) ? seen : []).map(key).filter(Boolean)), out = [];
  for (const v of list) {
    const k = key(v.text);
    if (v.text.length <= 20 || !k || old.has(k)) continue;
    old.add(k);
    out.push({ angle: v.angle, label: DESC_LABEL[v.angle] || "", text: v.text });
    if (out.length >= DESC_N) break;
  }
  return out;
}
