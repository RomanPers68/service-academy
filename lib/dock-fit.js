// lib/dock-fit.js — v65 (Доп. 378): размер кружков ленты инструментов на главной (Справочник, Меню, Глоссарий,
// Чек-листы, у руководителя ещё AI-интервью) под ширину ряда.
// w — ширина ряда инструментов (без SOS), l — ширина самой длинной подписи, n — сколько инструментов,
// base — наибольший кружок (36 px, на узком экране 34). У каждого кружка поля 2 + 2 px, между кружками 2 px,
// у раскрытой подписи поля 5 + 5 px. Влезает с подписью при кружке не меньше 28 px — подписи ездят по очереди,
// как раньше; не влезает — только значки (подписи не раскрываются), кружки — сколько поместится, от 26 px.
export const DOCK_MIN = 28;
export function dockFit(w, l, n, base) {
  if (!w || !l || !n) return { ring: base, labels: true };
  const fit = Math.floor((w - (n - 1) * 2 - n * 4 - (l + 10)) / n);
  if (fit >= DOCK_MIN) return { ring: Math.min(base, fit), labels: true };
  return { ring: Math.max(26, Math.min(base, Math.floor((w - (n - 1) * 2 - n * 4) / n))), labels: false };
}
