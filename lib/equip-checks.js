// модуль 18). Раз в неделю администратор проверяет график мойки льдогенератора и пивных линий, раз в месяц управляющий —
// состояние оборудования и закрытие заявок в Битрикс24. Стандарт не называет день, поэтому напоминаем по понедельникам:
// каждый понедельник — недельная проверка, в первый понедельник месяца — ещё и месячная. Строка ведёт в урок «Контроль»
// темы менеджера (m9-7), если тема есть в программе.

export const EQP_WEEK = { k: "eqp-week", title: "Раз в неделю: график мойки льдогенератора и пивных линий",
  sub: "Бункер льдогенератора не реже раза в месяц, пивные линии не реже раза в 14 дней и при смене сорта" };
export const EQP_MONTH = { k: "eqp-month", title: "Раз в месяц: оборудование и заявки в Битрикс24",
  sub: "Состояние техники и закрыты ли заявки о поломках" };
export const EQP_LESSON = { mod: "m9", id: "m9-7" };

/** day — «ГГГГ-ММ-ДД» (день заведения из сводки). Не понедельник или не дата — пусто. */
export function eqpChecks(day) {
  const s = String(day || "");
  if (!/^\d{4}-\d{2}-\d{2}$/.test(s)) return [];
  const [y, m, d] = s.split("-").map(Number);
  const dt = new Date(Date.UTC(y, m - 1, d));
  if (isNaN(dt) || dt.getUTCDate() !== d || dt.getUTCDay() !== 1) return [];
  return d <= 7 ? [EQP_WEEK, EQP_MONTH] : [EQP_WEEK];
}
