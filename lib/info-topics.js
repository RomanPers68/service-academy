export const INFO_LABEL = "для ознакомления";
export const INFO_NOTE = "Тема для ознакомления: в прогресс трека и отчёт руководителя не входит";

/** модуль (или запись индекса уроков) — тема для ознакомления */
export const isInfo = (m) => !!(m && m.info);

/** темы, которые считаются: прогресс, «Дальше», задания дня (без тем для ознакомления) */
export const countable = (mods) => (Array.isArray(mods) ? mods.filter((m) => m && !m.info) : []);

/** id всех шагов тем для ознакомления: урок, практика, сборка, диалог, тест */
export function infoLessonIds(mods) {
  const out = new Set();
  (Array.isArray(mods) ? mods : []).forEach((m) => { if (isInfo(m)) (m.lessons || []).forEach((l) => { if (l && l.id) out.add(l.id); }); });
  return out;
}

/** модуль по id шага — для решения «тема для ознакомления?» там, где под рукой только урок */
export function moduleOfLesson(mods, id) {
  if (!id) return null;
  return (Array.isArray(mods) ? mods : []).find((m) => m && (m.lessons || []).some((l) => l && l.id === id)) || null;
}
