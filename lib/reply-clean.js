// lib/reply-clean.js — v76 (Доп. 389), v77 (Доп. 390): ответ ИИ на экране. Без React — проверяют тесты.
// Чат Наставника понимает только **жирный** и переносы строк, а модели присылают Markdown: заголовки «###»,
// маркеры «-» и «*», черту «---», *курсив* и цифры-эмодзи «1️⃣» вместо номеров. На экране это висело бы
// решётками и звёздочками, поэтому разметку переводим в то, что чат показывает.
// v77: тон ответа не трогаем. В v76 здесь же убирались эмодзи, «Отличный вопрос!» и «Надеюсь, помог» —
// владелец вернул Наставнику человечность: смайлики и тёплые фразы остаются, как их написала модель.

// Видимые эмодзи — как в проверках v75: знаки с эмодзи-видом по умолчанию и любые пиктограммы с U+FE0F,
// вместе с оттенками кожи и склейками через ZWJ. Типографские ✓ ✕ ★ › · не трогаем.
const EMOJI_RE = /(?:\p{Emoji_Presentation}|\p{Extended_Pictographic}\uFE0F)(?:\p{Emoji_Modifier}|\uFE0F|\u200D(?:\p{Emoji_Presentation}|\p{Extended_Pictographic})\uFE0F?)*/gu;
const KEYCAP_RE = /([0-9])\uFE0F?\u20E3/gu;                       // цифра-эмодзи в начале пункта → «1.»

// Реплики живого гостя: эмодзи гость не «говорит» — их убираем (Наставнику — оставляем, см. выше)
export function stripEmoji(text) {
  return String(text || "").replace(KEYCAP_RE, "$1.").replace(EMOJI_RE, "").replace(/[ \t]{2,}/g, " ");
}

// Разметка → то, что видно в чате: тон, смайлики и слова — как у модели
export function cleanReply(text) {
  let t = String(text || "").replace(/\r\n?/g, "\n");
  t = t.replace(/^([ \t]*)([0-9])\uFE0F?\u20E3[ \t]*/gm, "$1$2. ");                    // «1️⃣ Пункт» → «1. Пункт»
  t = t.replace(/^[ \t]*([-*_])(?:[ \t]*\1){2,}[ \t]*$/gm, "");                         // «---», «* * *»
  t = t.replace(/^[ \t]{0,3}#{1,6}[ \t]+(.+?)[ \t]*#*[ \t]*$/gm, (_, h) => (/\*\*/.test(h) ? h : `**${h}**`));   // заголовок → жирная строка
  t = t.replace(/^[ \t]*[-*+][ \t]+/gm, "• ");                                          // «- пункт», «* пункт» → «• пункт»
  t = t.replace(/(^|[^*\p{L}\p{N}])\*(?![\s*])([^*\n]+?)(?<!\s)\*(?!\*)/gu, "$1$2");    // *курсив* — без звёздочек
  return t.replace(/[ \t]+$/gm, "").replace(/^[ \t]+/gm, "").replace(/\n{3,}/g, "\n\n").trim();
}

// Реплика живого гостя: «*смотрит на часы* Простите, горячее скоро?» → действие отдельно, без звёздочек.
// Незакрытая звёздочка в конце — действие, которое ещё печатается (ответ идёт потоком).
export function splitActions(text) {
  const s = String(text || "");
  const out = [];
  const re = /\*([^*\n]+)\*|\*([^*\n]*)$/g;
  let last = 0, m;
  const push = (t, act) => { const v = act ? t.trim() : stripEmoji(t).trim(); if (v) out.push({ t: v, act }); };
  while ((m = re.exec(s))) {
    push(s.slice(last, m.index), false);
    push(m[1] != null ? m[1] : m[2], true);
    last = m.index + m[0].length;
    if (!m[0].length) re.lastIndex++;
  }
  push(s.slice(last), false);
  return out;
}
