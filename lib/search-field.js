// v173 (Доп. 498), владелец: «Заметил артефакт в поиске, когда пишешь а после скролишь. На записи видно.»
// На записи набрано «Эсп», и на месте слова остаётся серая плашка: список листается, а она стоит на экране.
// Это подсветка автозамены iPhone: клавиатура собиралась заменить «Эсп» на «Эми» и пометила слово. Метку рисует
// система поверх страницы, а экран у нас листается внутри #root (ui/css.js), и за такой прокруткой метка не едет
// (ошибки WebKit 138201 и 236588). В строке поиска автозамена и не нужна: она же подменяет «негрони» и «ристретто»
// чужими словами. Поэтому в поиске нет ни автозамены, ни красного подчёркивания.
// Клавиша ввода подписана «Найти»: на телефоне она убирает клавиатуру, и список виден целиком (на записи под
// клавиатурой помещалось три карточки, а другой клавиши, чтобы её убрать, не было). На компьютере убирать нечего,
// поле остаётся в работе.
// Применение: {...SEARCH_ATTRS} последним в <input> строки поиска. Обычным полям (заметки, названия) это не нужно.

/** Поле, где ищут, а не пишут текст: без автозамены и без подчёркивания «ошибок». */
export const NO_AUTOCORRECT = { autoCorrect: "off", spellCheck: false };

/** Клавиатура на экране? Палец как основной указатель: телефон или планшет. */
export function touchKeyboard(win) {
  try {
    const w = win || (typeof window !== "undefined" ? window : null);
    return !!(w && typeof w.matchMedia === "function" && w.matchMedia("(pointer: coarse)").matches);
  } catch (e) { return false; }
}

/** «Найти» на клавиатуре телефона: убирает клавиатуру. Набор иероглифов и подсказок (isComposing) не трогаем. */
export function searchKeyDown(e, win) {
  if (!e || e.key !== "Enter" || e.isComposing) return false;
  const el = e.currentTarget || e.target;
  if (!touchKeyboard(win) || !el || typeof el.blur !== "function") return false;
  el.blur();
  return true;
}

/** Свойства строки поиска. */
export const SEARCH_ATTRS = { ...NO_AUTOCORRECT, enterKeyHint: "search", onKeyDown: (e) => { searchKeyDown(e); } };
