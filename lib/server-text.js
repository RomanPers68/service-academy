// lib/server-text.js — v58 (Доп. 371): что сказать человеку, когда сервер не ответил.
// Раньше в экранах жили надписи для разработчика: «Нужен stage14 на сервере», «примени supabase-stage15…»,
// «после этапа 24». Сотрудник их видел и не знал, что делать. Теперь текст — человеческий, а подсказка
// про SQL-скрипт — только владельцу (is_admin): он один может что-то с ней сделать.
// Чистые функции — их проверяют тесты в Node.

const cap = (s) => (s ? s[0].toUpperCase() + s.slice(1) : s);

// Сервер ещё не обновлён (функции нет).
//   what — что появится («отчёты», «общая лига»), many — «появятся» (множественное), admin — показывать ли
//   скрипт, sql — имя файла этапа
export function serverMissing({ what = "это", many = false, admin = false, sql = null, who = "владелец" } = {}) {
  const base = cap(what) + (many ? " появятся" : " появится") + ", когда " + who + " обновит сервер.";
  return admin && sql ? base + " Для владельца: примени " + sql + " в Supabase → SQL Editor." : base;
}

// Сервер ответил ошибкой или ещё подхватывает обновление (PGRST202).
export function serverError({ code = null, message = null, admin = false } = {}) {
  if (code === "PGRST202") {
    return admin
      ? "Сервер ещё не видит новые функции. В Supabase → SQL Editor выполни одну строку: notify pgrst, 'reload schema'; — и открой этот экран заново."
      : "Сервер ещё подхватывает обновление — открой этот экран чуть позже.";
  }
  if (message) {
    return admin
      ? "Сервер ответил ошибкой: " + message + (code ? " (" + code + ")" : "") + ". Пришли этот текст разработчику."
      : "Сервер ответил ошибкой — попробуй позже. Если повторится, скажи владельцу.";
  }
  return "Нет связи с сервером — попробуй ещё раз.";
}

// Короткая форма для подписей и ошибок действия: «Сервер не обновлён» + скрипт только владельцу
export function serverStage({ admin = false, sql = null, stage = null } = {}) {
  const hint = admin ? (sql ? " — примени " + sql : stage ? " — нужен этап " + stage : "") : "";
  return "Сервер ещё не обновлён" + hint + (admin ? "." : " — скажи владельцу.");
}
