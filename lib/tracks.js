// Тёмные варианты цветов треков для светлой темы (правка 170): на креме светлые цвета
// дают контраст 1,9–2,6 при норме 3,0 для крупных надписей и 4,5 для обычных.
const INK_BY_COLOR = { "#7c9e87": "#33573E", "#c8a96e": "#7A5A1E", "#c8917a": "#8A4A36",
  "#8b7bab": "#54467A", "#7b8fab": "#44587A", "#c8a050": "#765E2F" };
// В тёмной теме самые тёмные цвета треков (фиолетовый, синий) на карточках дают 4,0–4,3
const BRIGHT_BY_COLOR = { "#8b7bab": "#9E8FC0", "#7b8fab": "#8FA3C0" };
export const inkOf = (color, light) => {
  const k = String(color || "").toLowerCase();
  return light ? (INK_BY_COLOR[k] || color) : (BRIGHT_BY_COLOR[k] || color);
};
