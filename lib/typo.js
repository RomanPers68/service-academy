// lib/typo.js — v150 (Доп. 474): неразрывные пробелы в текстах уроков и «О нас», как уже сделано в советах (ui/lesson-tip.jsx):
// короткие слова и числа не остаются в конце строки («в зале», «3 см», «0,5 л»), тире не начинает строку («— временно»).
// Правило коротких слов — как msTie (ui/mastery-card.jsx); два прохода, чтобы склеились и цепочки («и в зале»).
// Текст урока приходит кусками (термины, **жирное**), поэтому и пробел в конце куска («в » перед **залом**) — неразрывный.
const SHORT = /(^|[\s («])([А-Яа-яЁё]{1,2}|\d+(?:[.,]\d+)?)[ \t]+(?=\S|$)/g;
export function typo(t) {
  if (typeof t !== "string" || !t) return t;
  return t.replace(SHORT, "$1$2 ").replace(SHORT, "$1$2 ").replace(/[ \t]+(—|–)(?=\s|$)/g, " $1");
}
